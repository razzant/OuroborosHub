// Focused real MV3 regression for first input in a hidden, disposable tab.
// This headless test does not reproduce or certify the owner's headed Chrome.
import assert from 'node:assert/strict';
import { execFileSync, spawn } from 'node:child_process';
import fs from 'node:fs';
import net from 'node:net';
import path from 'node:path';
import test from 'node:test';

import { FakeHost, freePort, installReplica, launchChromium, sleep, startFixtureServer, until } from './harness.mjs';

const executable = process.env.OUROBOROS_CHROME_TEST_CHROMIUM;

test('MV3 prepares the hidden renderer before first input, once per document and attachment',
  { skip: executable ? false : 'OUROBOROS_CHROME_TEST_CHROMIUM is not set', timeout: 120000 }, async () => {
    assert.ok(!/headless[_-]shell/i.test(executable));
    const root = fs.mkdtempSync('/tmp/ob-input-frame-');
    const install = installReplica(root);
    const setupEnv = { PATH: process.env.PATH, OUROBOROS_SKILL_STATE_DIR: install.stateDir };
    const setupScript = path.join(install.skillDir, 'scripts/setup.mjs');
    const setup = (...args) => JSON.parse(execFileSync(process.execPath, [setupScript, ...args], { env: setupEnv, encoding: 'utf8' }));
    const fixture = await startFixtureServer();
    const profile = fs.mkdtempSync(path.join(root, 'profile-'));
    let browser;
    let host;
    try {
      const init = setup('init', '--port', String(await freePort()));
      const credential = JSON.parse(fs.readFileSync(init.credential_file, 'utf8')).credential;
      browser = await launchChromium({ executable, profile, extension: path.join(install.skillDir, 'extension'), WebSocket: install.WebSocket });
      const { cdp } = browser;
      const worker = await until(async () => (await cdp.send('Target.getTargets')).targetInfos
        .find((target) => target.type === 'service_worker' && target.url.endsWith('/service_worker.js')),
      { what: 'MV3 service worker' });
      const target = await cdp.open(`${fixture.origin}/a.html`);
      const foreground = await cdp.open(`${fixture.origin}/fg.html`, { background: true });

      // The popup is the existing owner's pairing and sharing path, with a
      // temporary credential generated by setup in the disposable replica.
      await target.activate();
      let popup = await cdp.open(`chrome-extension://${init.extension_id}/popup.html`, { background: true });
      await until(async () => (await popup.evaluate('document.getElementById("tab").textContent')) !== '…', { what: 'popup tab' });
      const pairing = spawn(process.execPath, [setupScript, 'pair', '--wait', '30'], { env: setupEnv, stdio: ['ignore', 'pipe', 'pipe'] });
      let pairOutput = '';
      pairing.stdout.on('data', (part) => { pairOutput += part; });
      const pairDone = new Promise((resolve) => pairing.once('exit', resolve));
      await until(() => new Promise((resolve) => {
        const probe = net.connect(init.port, '127.0.0.1');
        probe.once('connect', () => { probe.destroy(); resolve(true); });
        probe.once('error', () => resolve(false));
      }), { what: 'pairing listener' });
      await popup.evaluate(`document.getElementById('port').value = ${JSON.stringify(String(init.port))}`);
      await popup.typeInto('#credential', credential);
      await popup.click('#save');
      assert.equal(await pairDone, 0, pairOutput);
      assert.equal(JSON.parse(pairOutput).ok, true);
      await popup.close();

      host = new FakeHost({ socketDir: root, skillDir: install.skillDir, env: { OUROBOROS_SKILL_STATE_DIR: install.stateDir } });
      await host.start();
      assert.equal((await host.call('browser_state', {}, { invocationId: null })).json.pairing.listener, 'listening');
      await target.activate();
      popup = await cdp.open(`chrome-extension://${init.extension_id}/popup.html`, { background: true });
      await until(async () => /Connected/.test(await popup.evaluate('document.getElementById("summary").textContent')),
        { what: 'paired executor' });
      await popup.click('#share');
      await until(async () => (await host.call('browser_state', {}, { invocationId: null })).json.approved_tabs.length === 1,
        { what: 'shared target' });
      const tabId = (await host.call('browser_state', {}, { invocationId: null })).json.approved_tabs[0].tab_id;
      await foreground.activate();
      assert.equal(await target.evaluate('document.visibilityState'), 'hidden');
      assert.equal(await target.evaluate('document.hasFocus()'), false);
      assert.equal((await host.call('browser_connect', { tab_id: tabId })).isError, false);

      // Instrument only the temporary extension worker. The wrapper observes
      // actual chrome.debugger commands and can synthesize a missing or held
      // capture result; it never changes the source under test.
      const attached = await cdp.send('Target.attachToTarget', { targetId: worker.targetId, flatten: true });
      const workerSession = attached.sessionId;
      await cdp.send('Runtime.enable', {}, workerSession);
      const inWorker = async (expression) => {
        const answer = await cdp.send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true }, workerSession);
        if (answer.exceptionDetails) throw new Error(answer.exceptionDetails.text);
        return answer.result.value;
      };
      await inWorker(`(() => {
        globalThis.__frameTrace = [];
        globalThis.__frameFault = '';
        const original = chrome.debugger.sendCommand.bind(chrome.debugger);
        chrome.debugger.sendCommand = (target, method, params) => {
          if (method === 'Page.captureScreenshot' || method.startsWith('Input.')
              || method === 'Target.activateTarget' || method === 'Emulation.setFocusEmulationEnabled')
            globalThis.__frameTrace.push({ method, type: params?.type || null });
          if (method === 'Page.captureScreenshot' && globalThis.__frameFault === 'missing') return Promise.resolve({ data: '' });
          if (method === 'Page.captureScreenshot' && globalThis.__frameFault === 'held')
            return new Promise((resolve) => { globalThis.__pendingFrameResolve = resolve; });
          return original(target, method, params);
        };
        return true;
      })()`);
      const trace = () => inWorker('globalThis.__frameTrace');
      const fault = (value) => inWorker(`globalThis.__frameFault = ${JSON.stringify(value)}`);
      const action = (operation, args = {}) => host.call('browser_action', { operation, args });
      const count = () => target.evaluate('Number(document.getElementById("count").textContent)');
      const firstInput = (events) => events.findIndex((event) => event.method.startsWith('Input.'));
      const captures = (events) => events.filter((event) => event.method === 'Page.captureScreenshot').length;
      const noPixels = (reply) => {
        assert.equal(reply.images.length, 0, 'frame preparation must not return an image');
        assert.ok(!JSON.stringify(reply.json).includes('iVBORw0KGgo'), 'capture pixels leaked into MCP response');
        assert.ok(!JSON.stringify(reply.json).includes('data:image/png'), 'capture data URL leaked into MCP response');
      };

      const first = await action('click', { selector: '#go' });
      assert.equal(first.isError, false, JSON.stringify(first.json));
      assert.equal(first.json.result.input_preparation.kind, 'renderer_frame');
      noPixels(first);
      assert.equal(await count(), 1, 'the first acknowledged click must change the page');
      const events = await target.evaluate('window.events');
      assert.deepEqual(events.filter((event) => event.target === 'go' && ['pointerdown', 'mousedown', 'mouseup', 'click'].includes(event.type))
        .map((event) => [event.type, event.trusted]),
      [['pointerdown', true], ['mousedown', true], ['mouseup', true], ['click', true]]);
      assert.equal(await target.evaluate('document.visibilityState'), 'hidden');
      assert.equal(await foreground.evaluate('document.visibilityState'), 'visible');
      assert.equal(await foreground.evaluate('window.blurs'), 0);
      let calls = await trace();
      assert.ok(calls.every((event) => !['Target.activateTarget', 'Emulation.setFocusEmulationEnabled'].includes(event.method)),
        'worker must not activate the tab or emulate focus');
      assert.equal(captures(calls), 1);
      assert.equal(calls[0].method, 'Page.captureScreenshot');
      assert.ok(firstInput(calls) > 0, JSON.stringify(calls));

      const second = await action('click', { selector: '#go' });
      assert.equal(second.isError, false, JSON.stringify(second.json));
      assert.equal(await count(), 2);
      assert.equal(captures(await trace()), 1, 'same document must reuse the prepared frame');
      const key = await action('press', { key: 'Tab' });
      assert.equal(key.isError, false, JSON.stringify(key.json));
      assert.equal(captures(await trace()), 1, 'keyboard input must reuse the prepared frame');

      const navigated = await action('navigate', { url: `${fixture.origin}/a.html?fresh=1` });
      assert.equal(navigated.isError, false, JSON.stringify(navigated.json));
      assert.equal(await count(), 0);
      const beforeFresh = (await trace()).length;
      const fresh = await action('click', { selector: '#go' });
      assert.equal(fresh.isError, false, JSON.stringify(fresh.json));
      noPixels(fresh);
      assert.equal(await count(), 1);
      calls = await trace();
      assert.equal(captures(calls), 2, 'a new document needs a new frame');
      assert.equal(calls[beforeFresh].method, 'Page.captureScreenshot');
      assert.ok(firstInput(calls.slice(beforeFresh)) > 0);
      const filled = await action('fill', { selector: '#name', text: 'Agent value' });
      assert.equal(filled.isError, false, JSON.stringify(filled.json));
      assert.equal(await target.evaluate('document.getElementById("name").value'), 'Agent value');
      assert.equal(captures(await trace()), 2);

      const handoff = await host.call('browser_handoff');
      assert.equal(handoff.isError, false, JSON.stringify(handoff.json));
      assert.equal(handoff.json.last_closure.debugger_detach_ack, true);
      const whileClosed = await action('click', { selector: '#go' });
      assert.equal(whileClosed.isError, true);
      assert.equal(await count(), 1);
      await target.typeInto('#name', ' plus owner');
      assert.equal(await target.evaluate('document.getElementById("name").value'), 'Agent value plus owner');
      const resumed = await host.call('browser_resume');
      assert.equal(resumed.isError, false, JSON.stringify(resumed.json));
      assert.equal(await target.evaluate('document.getElementById("name").value'), 'Agent value plus owner',
        'handoff and resume preserve the same form document');
      const beforeAttachment = (await trace()).length;
      const onAttachment = await action('click', { selector: '#go' });
      assert.equal(onAttachment.isError, false, JSON.stringify(onAttachment.json));
      noPixels(onAttachment);
      assert.equal(await count(), 2);
      calls = await trace();
      assert.equal(captures(calls), 3, 'a new attachment needs a new frame');
      assert.equal(calls[beforeAttachment].method, 'Page.captureScreenshot');
      assert.ok(firstInput(calls.slice(beforeAttachment)) > 0);

      await fault('missing');
      assert.equal((await action('navigate', { url: `${fixture.origin}/a.html?missing=1` })).isError, false);
      const beforeMissing = (await trace()).length;
      const missing = await action('click', { selector: '#go' });
      assert.equal(missing.isError, true);
      assert.equal(missing.json.error.code, 'BROWSER_INPUT_NOT_READY');
      assert.equal(missing.json.steps[0].outcome, 'not_dispatched');
      assert.equal(await count(), 0);
      assert.deepEqual((await trace()).slice(beforeMissing).map((event) => event.method), ['Page.captureScreenshot']);
      await fault('');
      const recovered = await action('click', { selector: '#go' });
      assert.equal(recovered.isError, false, JSON.stringify(recovered.json));
      assert.equal(await count(), 1);

      await fault('held');
      assert.equal((await action('navigate', { url: `${fixture.origin}/a.html?timeout=1` })).isError, false);
      const beforeTimeout = (await trace()).length;
      const timedOut = await action('click', { selector: '#go' });
      assert.equal(timedOut.isError, true);
      assert.equal(timedOut.json.error.code, 'BROWSER_INPUT_NOT_READY');
      assert.equal(timedOut.json.steps[0].outcome, 'not_dispatched');
      assert.equal(await count(), 0);
      assert.deepEqual((await trace()).slice(beforeTimeout).map((event) => event.method), ['Page.captureScreenshot']);

      // The timeout has ended the step. A new held preparation is cut by the
      // real handoff; neither it nor a queued click may dispatch input.
      const beforeRevoked = (await trace()).length;
      const pending = action('click', { selector: '#go' });
      await until(async () => (await trace()).length > beforeRevoked, { what: 'held frame capture' });
      const closed = await host.call('browser_handoff');
      assert.equal(closed.json.last_closure.debugger_detach_ack, true);
      await inWorker('globalThis.__pendingFrameResolve({data:"late-frame-after-handoff"}); true');
      const revoked = await pending;
      assert.equal(revoked.isError, true);
      assert.equal(revoked.json.steps[0].outcome, 'not_dispatched');
      assert.equal(await count(), 0);
      assert.deepEqual((await trace()).slice(beforeRevoked).map((event) => event.method), ['Page.captureScreenshot']);
      assert.equal(host.violations.length, 0, JSON.stringify(host.violations));
      console.log('INPUT_FRAME_HEADLESS_MV3_PASS: first trusted click, geometry, reuse, fresh document, closure, faults');
    } finally {
      if (host) await host.stop();
      if (browser) await browser.close();
      await fixture.close();
      fs.rmSync(root, { recursive: true, force: true });
    }
  });

DRAFT_FIELDS = {
    "view", "query", "site", "published_after", "published_before",
    "acquired_after", "acquired_before", "mode", "url", "question",
    "live", "max_chars", "filter_open", "read_advanced",
}
_BOOL_FIELDS = {"live", "filter_open", "read_advanced"}
_DRAFT_MAX_BYTES = 24_000


def _api_key() -> str:
    try:
        values = _api.get_settings(["KEENABLE_API_KEY"]) if _api else {}
        return str(values.get("KEENABLE_API_KEY") or "").strip() if isinstance(values, dict) else ""
    except Exception:
        return ""


def _tool_search(ctx: Any = None, **kwargs: Any) -> str:
    return json.dumps(client_search(kwargs, _api_key()), ensure_ascii=False)


def _tool_fetch(ctx: Any = None, **kwargs: Any) -> str:
    return json.dumps(client_fetch(kwargs, _api_key(), content_char_limit=CONTENT_CHAR_LIMIT), ensure_ascii=False)


def _notes(payload: Dict[str, Any]) -> list[str]:
    notes = []
    if payload.get("parse_status") in {"partial", "unparsed"}:
        notes.append("Some returned material could not be parsed. Inspect the raw response in Details.")
    if payload.get("results_omitted"):
        notes.append(f"{payload['results_omitted']} additional results did not fit the tool's text budget.")
    if any(isinstance(row, dict) and row.get("snippet_truncated") for row in payload.get("results", [])):
        notes.append("Some snippets reached the tool's text limit; read the source for more.")
    for name, observed in (payload.get("filter_observations") or {}).items():
        if observed.get("conclusion") == "observed_conflict":
            notes.append(f"Returned dates conflict with the requested {name.replace('_', ' ')} filter.")
        elif observed.get("conclusion") == "not_verifiable":
            notes.append(f"Returned metadata cannot verify the {name.replace('_', ' ')} filter.")
    if payload.get("content_truncated_by_skill") or "at_effective_cap" in payload.get("content_incompleteness_indicators", []):
        notes.append("The text reaches its limit and may continue. Ask a focused question about the page.")
    if "served_url_differs_from_request" in payload.get("content_incompleteness_indicators", []):
        notes.append("The served URL differs from the requested URL. Compare them in Details; it may be a redirect, canonical page or access screen.")
    if "body_under_500_chars" in payload.get("content_incompleteness_indicators", []):
        notes.append("The returned text is short; it may be a short page or an incomplete extraction.")
    if payload.get("max_chars_clamped"):
        notes.append(f"The requested limit was reduced to {payload.get('max_chars_effective')} characters.")
    return notes


def _present(payload: Dict[str, Any]) -> Dict[str, Any]:
    view = dict(payload)
    view["ui_notes"] = _notes(payload)
    if not payload.get("ok"):
        guidance = _ERROR_GUIDANCE.get(str(payload.get("error")), "The request failed. Inspect Details or retry.")
        view["ui_guidance"] = guidance
    return view


def _write_json(directory: Optional[Path], name: str, value: Dict[str, Any]) -> None:
    if directory is None:
        raise OSError("Skill state storage is unavailable")
    directory.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=directory, prefix=".keenable-", suffix=".tmp", delete=False) as stream:
            temporary = Path(stream.name)
            json.dump(value, stream, ensure_ascii=False)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, directory / name)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def _read_json(directory: Optional[Path], name: str) -> Dict[str, Any]:
    if directory is None:
        raise OSError("Skill state storage is unavailable")
    path = directory / name
    if not path.exists():
        return {}
    result = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(result, dict):
        raise ValueError("Saved widget state is not an object")
    return result


def _validated_draft(value: Any) -> Dict[str, Any]:
    if not isinstance(value, dict):
        raise ValueError("Draft must be an object")
    if len(json.dumps(value, ensure_ascii=False).encode("utf-8")) > _DRAFT_MAX_BYTES:
        raise ValueError("Draft is too large to save")
    if set(value) - DRAFT_FIELDS:
        raise ValueError("Draft contains unknown fields")
    for name, item in value.items():
        if name in _BOOL_FIELDS:
            if not isinstance(item, bool):
                raise ValueError(f"{name} must be a boolean")
        elif name == "max_chars":
            if isinstance(item, bool) or not isinstance(item, (int, str)):
                raise ValueError("max_chars must be a number or a numeric draft")
        elif not isinstance(item, str) or len(item) > 8_000:
            raise ValueError(f"{name} must be a short string")
    if value.get("view", "search") not in {"search", "read"}:
        raise ValueError("Unknown view")
    if value.get("mode", "pro") not in {"pro", "realtime"}:
        raise ValueError("Unknown search mode")
    return dict(value)


def _operation(slot: str, arguments: Dict[str, Any], key: str, directory: Optional[Path]) -> Dict[str, Any]:
    # Persistence is inside the worker: browser disposal may cancel the awaiting
    # route, but the already-started vendor call can still finish and save here.
    result = client_search(arguments, key) if slot == "search" else client_fetch(arguments, key, content_char_limit=CONTENT_CHAR_LIMIT)
    view = _present(result)
    try:
        _write_json(directory, f"widget-{slot}.json", {"request": arguments, "result": view})
    except (OSError, ValueError, TypeError):
        view["ui_state_warning"] = "This result could not be saved. It may be lost when the widget closes."
    return view


async def _json_body(request: Any) -> Dict[str, Any]:
    data = await request.json()
    if not isinstance(data, dict):
        raise ValueError("Request must be a JSON object")
    return data


def _json_response(payload: Dict[str, Any], status: int = 200) -> Any:
    try:
        from starlette.responses import JSONResponse
    except ImportError:
        return payload
    return JSONResponse(payload, status_code=status, headers={"Cache-Control": "no-store"})


async def _route_search(request: Any) -> Any:
    try:
        body = await _json_body(request)
    except (ValueError, TypeError):
        return _json_response({"ok": False, "message": "Enter a valid search request."}, 400)
    return _json_response(await asyncio.to_thread(_operation, "search", body, _api_key(), _state_dir))


async def _route_fetch(request: Any) -> Any:
    try:
        body = await _json_body(request)
    except (ValueError, TypeError):
        return _json_response({"ok": False, "message": "Enter a valid page request."}, 400)
    slot = "answer" if body.get("prompt") else "page"
    return _json_response(await asyncio.to_thread(_operation, slot, body, _api_key(), _state_dir))


def _load_state(directory: Optional[Path]) -> Dict[str, Any]:
    result = {"draft": _read_json(directory, "widget-draft.json"), "results": {}}
    for slot in ("search", "page", "answer"):
        item = _read_json(directory, f"widget-{slot}.json")
        if item:
            result["results"][slot] = item
    return result


async def _route_state(request: Any) -> Any:
    try:
        if request.method == "GET":
            return _json_response(await asyncio.to_thread(_load_state, _state_dir))
        body = await _json_body(request)
        draft = _validated_draft(body.get("draft"))
        await asyncio.to_thread(_write_json, _state_dir, "widget-draft.json", draft)
        return _json_response({"ok": True})
    except (ValueError, TypeError):
        return _json_response({"ok": False, "message": "Widget state is invalid or too large."}, 400)
    except OSError:
        return _json_response({"ok": False, "message": "Widget state could not be read or saved."}, 503)


async def _route_author_kit(request: Any) -> Any:
    try:
        from ouroboros.server_web import read_author_kit_assets
        assets = await asyncio.to_thread(read_author_kit_assets, request.app.state.repo_dir)
        return _json_response({"ok": True, "css": assets["css"]})
    except (ImportError, AttributeError, OSError, KeyError):
        return _json_response({"ok": False, "message": "Shared appearance unavailable; native controls remain usable."})


def _on_unload() -> None:
    global _api, _state_dir
    reset_session_cache()
    _api = None
    _state_dir = None


def register(api: Any) -> None:
    global _api, _state_dir
    _api = api
    try:
        _state_dir = Path(api.get_state_dir())
    except (AttributeError, TypeError):
        _state_dir = None
    api.register_tool("search_web_pages", handler=_tool_search, description=_SEARCH_DESCRIPTION, schema=_SEARCH_SCHEMA, timeout_sec=90)
    api.register_tool("fetch_page_content", handler=_tool_fetch, description=_FETCH_DESCRIPTION, schema=_FETCH_SCHEMA, timeout_sec=90)
    api.register_route("search", handler=_route_search, methods=("POST",))
    api.register_route("fetch", handler=_route_fetch, methods=("POST",))
    api.register_route("state", handler=_route_state, methods=("GET", "POST"))
    api.register_route("author-kit", handler=_route_author_kit, methods=("GET",))
    api.register_ui_tab("keenable", title="Keenable", render=_UI_RENDER)
    api.on_unload(_on_unload)
